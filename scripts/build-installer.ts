// `bun run build-installer`: builds the app and packs it, with the small server, into one Windows program:
// release/Dashcam Viewer Installer.exe. Running that program serves the app on http://localhost:5191 and opens
// the browser to install it; the computer needs only Chrome or Edge (no Bun, no code).
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { build } from 'vite';
import { renderIcon } from './icon-art';
import { encodePng } from './png';

const OUT_DIR = '.installer';
const OUTFILE = 'release/Dashcam Viewer Installer.exe';

/** A Windows .ico holding one 256×256 PNG. */
function icoFromPng(png: Uint8Array): Uint8Array {
  const ico = new Uint8Array(22 + png.length);
  const v = new DataView(ico.buffer);
  v.setUint16(2, 1, true); // type: icon
  v.setUint16(4, 1, true); // one image
  // width and height 0 mean 256; no palette
  v.setUint16(10, 1, true); // planes
  v.setUint16(12, 32, true); // bits per pixel
  v.setUint32(14, png.length, true);
  v.setUint32(18, 22, true);
  ico.set(png, 22);
  return ico;
}

await build({ logLevel: 'warn' });

const dist = 'dist';
const files = readdirSync(dist, { recursive: true, withFileTypes: true })
  .filter((d) => d.isFile())
  .map((d) => relative(dist, join(d.parentPath, d.name)).replaceAll('\\', '/'));

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
mkdirSync('release', { recursive: true });

// The program's entry: every built file embedded (`type: 'file'`), served by scripts/serve-app.ts.
const imports = files.map((f, i) => `import f${i} from '../dist/${f}' with { type: 'file' };`).join('\n');
const entries = files.map((f, i) => `  ['/${f}', Bun.file(f${i})],`).join('\n');
writeFileSync(
  join(OUT_DIR, 'main.ts'),
  `// Generated by scripts/build-installer.ts: the Windows installer's entry, with the built app embedded.
import { runInstaller } from '../scripts/serve-app';
${imports}

const files = new Map<string, Blob>([
${entries}
]);

process.title = 'Dashcam Viewer';
const code = await runInstaller(files, !process.argv.includes('--no-open'));
if (code !== null) {
  // Started by double-click: leave the message on screen for a moment before the window closes.
  if (code === 0) await Bun.sleep(5000);
  else prompt('Press Enter to close.');
  process.exit(code);
}
`,
);
writeFileSync(join(OUT_DIR, 'icon.ico'), icoFromPng(encodePng(256, 256, renderIcon(256, false))));

const { version } = JSON.parse(readFileSync('package.json', 'utf8')) as { version: string };
const proc = Bun.spawnSync(
  [
    'bun',
    'build',
    '--compile',
    '--target=bun-windows-x64',
    `--windows-icon=${join(OUT_DIR, 'icon.ico')}`,
    '--windows-title=Dashcam Viewer Installer',
    '--windows-description=Installs Dashcam Viewer as an app on this computer',
    `--windows-version=${version}.0`,
    join(OUT_DIR, 'main.ts'),
    '--outfile',
    OUTFILE,
  ],
  { stdout: 'inherit', stderr: 'inherit' },
);
if (proc.exitCode !== 0) process.exit(proc.exitCode ?? 1);
console.log(`Wrote ${OUTFILE} (${files.length} app files inside).`);
